import { randomUUID } from 'node:crypto';
import { Prisma } from '../../src/generated/prisma/client.js';

// In-memory stand-in for PrismaService used by the e2e tests (plan D13): CI has
// no PostgreSQL, so it implements only the subset of the Prisma API the app uses.

type Row = Record<string, any>;
type Where = Record<string, unknown>;
type SortOrder = 'asc' | 'desc';
type OrderBy = Record<
  string,
  SortOrder | { sort: SortOrder; nulls?: 'first' | 'last' }
>;
type Omit = Record<string, boolean>;

function isOperator(condition: unknown): condition is Record<string, unknown> {
  return (
    condition instanceof Object &&
    !(condition instanceof Date) &&
    !Array.isArray(condition) &&
    ['lt', 'has', 'in', 'not'].some((key) => key in condition)
  );
}

// Unset fields behave like SQL NULL.
function equals(a: unknown, b: unknown): boolean {
  if (a instanceof Date && b instanceof Date)
    return a.getTime() === b.getTime();
  return (a ?? null) === (b ?? null);
}

function matchesCondition(value: unknown, condition: unknown): boolean {
  if (!isOperator(condition)) return equals(value, condition);
  if ('lt' in condition) return (value as any) < (condition.lt as any);
  if ('has' in condition) {
    return Array.isArray(value) && value.includes(condition.has);
  }
  if ('in' in condition) {
    return (condition.in as unknown[]).some((item) => equals(value, item));
  }
  return !equals(value, condition.not);
}

function matches(row: Row, where: Where = {}): boolean {
  return Object.entries(where).every(([field, condition]) =>
    matchesCondition(row[field], condition),
  );
}

function compare(a: Row, b: Row, orderBy: OrderBy[]): number {
  for (const order of orderBy) {
    const [field, spec] = Object.entries(order)[0];
    const { sort, nulls } = typeof spec === 'string' ? { sort: spec } : spec;
    const [left, right] = [a[field] ?? null, b[field] ?? null];
    if (left === null && right === null) continue;
    if (left === null || right === null) {
      // PostgreSQL default: nulls are larger than any value.
      const nullsFirst =
        (nulls ?? (sort === 'desc' ? 'first' : 'last')) === 'first';
      return (left === null) === nullsFirst ? -1 : 1;
    }
    if (equals(left, right)) continue;
    const result = left < right ? -1 : 1;
    return sort === 'desc' ? -result : result;
  }
  return 0;
}

function notFound(): Prisma.PrismaClientKnownRequestError {
  return new Prisma.PrismaClientKnownRequestError('Record not found.', {
    code: 'P2025',
    clientVersion: Prisma.prismaVersion.client,
  });
}

function uniqueViolation(field: string): Prisma.PrismaClientKnownRequestError {
  return new Prisma.PrismaClientKnownRequestError('Unique constraint failed.', {
    code: 'P2002',
    clientVersion: Prisma.prismaVersion.client,
    meta: { target: [field] },
  });
}

function project(row: Row, omit: Omit = {}): Row {
  const copy = { ...row };
  for (const [field, omitted] of Object.entries(omit)) {
    if (omitted) delete copy[field];
  }
  return copy;
}

interface FakeModelOptions {
  // Columns with a unique index besides the id.
  unique?: string[];
  // Column defaults applied on create, like the schema's @default values.
  defaults?: () => Row;
  // `id` is a UUID generated by the database instead of a sequence.
  uuid?: boolean;
}

export class FakeModel<T extends Row = Row> {
  rows: T[] = [];
  private nextId = 1;

  constructor(
    // Field used by update/delete and findUnique when `where` holds it.
    private readonly idField = 'id',
    private readonly timestamps: ('createdAt' | 'updatedAt')[] = [
      'createdAt',
      'updatedAt',
    ],
    private readonly options: FakeModelOptions = {},
  ) {}

  findMany(
    args: {
      where?: Where;
      orderBy?: OrderBy | OrderBy[];
      skip?: number;
      take?: number;
      omit?: Omit;
    } = {},
  ) {
    const orderBy = [args.orderBy ?? []].flat();
    const skip = args.skip ?? 0;
    const rows = this.rows
      .filter((row) => matches(row, args.where))
      .sort((a, b) => compare(a, b, orderBy))
      .slice(skip, args.take === undefined ? undefined : skip + args.take);
    return Promise.resolve(rows.map((row) => project(row, args.omit)));
  }

  findUnique(args: { where: Where; omit?: Omit }) {
    const row = this.rows.find((candidate) => matches(candidate, args.where));
    return Promise.resolve(row ? project(row, args.omit) : null);
  }

  create(args: { data: Row; omit?: Omit }) {
    const now = new Date();
    const row = { ...this.options.defaults?.(), ...args.data } as Row;
    if (this.idField === 'id' && row.id === undefined) {
      row.id = this.options.uuid ? randomUUID() : this.nextId++;
    }
    try {
      this.assertUnique(row);
    } catch (error) {
      return Promise.reject(error as Error);
    }
    for (const field of this.timestamps) row[field] = now;
    this.rows.push(row as T);
    return Promise.resolve(project(row, args.omit) as T);
  }

  update(args: { where: Where; data: Row; omit?: Omit }) {
    const row = this.rows.find((candidate) => matches(candidate, args.where));
    if (!row) return Promise.reject(notFound());
    try {
      this.assertUnique({ ...row, ...args.data }, row);
    } catch (error) {
      return Promise.reject(error as Error);
    }
    Object.assign(row, args.data);
    if (this.timestamps.includes('updatedAt')) {
      (row as Row).updatedAt = new Date();
    }
    return Promise.resolve(project(row, args.omit));
  }

  delete(args: { where: Where }) {
    const index = this.rows.findIndex((row) => matches(row, args.where));
    if (index === -1) return Promise.reject(notFound());
    const [row] = this.rows.splice(index, 1);
    return Promise.resolve({ ...row });
  }

  count(args: { where?: Where } = {}) {
    return Promise.resolve(
      this.rows.filter((row) => matches(row, args.where)).length,
    );
  }

  deleteMany(args: { where?: Where } = {}) {
    const before = this.rows.length;
    this.rows = this.rows.filter((row) => !matches(row, args.where));
    return Promise.resolve({ count: before - this.rows.length });
  }

  // Throws P2002 like PostgreSQL when another row already holds the value.
  private assertUnique(candidate: Row, self?: T): void {
    for (const field of this.options.unique ?? []) {
      const taken = this.rows.some(
        (row) => row !== self && equals(row[field], candidate[field]),
      );
      if (taken && candidate[field] != null) throw uniqueViolation(field);
    }
  }
}

